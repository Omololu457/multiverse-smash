// ben10VoiceMap.js: Ben 10 cast voice dispatch (ben10 / albedo humans, the READY aliens, Vilgax). Audio only; no gameplay effect.
// Uses the SAME mechanism as homelander_sfx_map.js, copied pool-for-pool, not a new one:
//   • Clip choice = juicePickVariant(hash(matchSeed, frame), player): a pure hash of (match seed, frame, player index).
//     never a random source, so LAN/replay pick the same clip on the same frame.
//   • Voice → sound.playSfxFile({ owner: fighter, fadeMs: 40 }): the engine's one-voice-per-character channel (a new
//     line cuts the old one with a 40 ms fade) + automatic music ducking. SFX pools layer freely (no owner).
//   • Pitch: ±3% voice, ±5% SFX (juicePitch). Per-pool cooldowns (frames) rate-limit chatter.
// Pools: ben10VoicePools.js (generated by tools/ben10/classify_vo.py from waveform analysis) + Albedo's / Vilgax's earlier
// TRANSCRIPT-verified packs (albedoVoice.js / vilgaxVoice.js arrays), merged into the matching pools. docs/ben10/AUDIO_MAP.md.
//
// WHO SPEAKS: a transformed Ben/Albedo speaks with the READY alien's pools (one alien = one voice, whichever device user
// transformed). Human Ben: the Classic variant → ben_young, Alien Force → ben_teen; Prime has no clips (silent). Albedo human →
// albedo. intro/win/lose fall back from an alien with no such pool to the device user's human pools.
// Cooldown timestamps live in a module WeakMap (render-side), never on the fighter / GAME_STATE.
import { sound, juicePickVariant, juicePitch } from "./sound.js"
import { BEN10_VO_POOLS } from "./ben10VoicePools.js"
import { ALBEDO_VOICE } from "./albedoVoice.js"
import { VILGAX_VOICE } from "./vilgaxVoice.js"

const merge = (a, b) => [...(a || []), ...(b || [])]
export const BEN10_VO = (() => {
  const P = JSON.parse(JSON.stringify(BEN10_VO_POOLS))
  const al = (P.albedo = P.albedo || {})
  al.INTRO = merge(ALBEDO_VOICE.intro, al.INTRO); al.TAUNT = merge(ALBEDO_VOICE.taunt, al.TAUNT)
  al.WIN = merge(ALBEDO_VOICE.win, al.WIN); al.LOW_HEALTH = merge(ALBEDO_VOICE.lowHealth, al.LOW_HEALTH)
  const vg = (P.vilgax = P.vilgax || {})
  vg.TAUNT = merge(VILGAX_VOICE.taunt, vg.TAUNT); vg.HIT_REACT = merge(VILGAX_VOICE.hitReact, vg.HIT_REACT)
  return P
})()

export const BEN10_VO_SFX_POOLS = new Set(["SFX"])
// event → the pools tried in order (first non-empty wins)
export const BEN10_VO_EVENTS = {
  intro: ["INTRO"], win: ["WIN"], lose: ["LOSE"], lowHealth: ["LOW_HEALTH"],
  transform: ["SPECIAL_CALLOUT", "TAUNT"], special: ["SPECIAL_CALLOUT", "ATTACK_EFFORT"],
  attack: ["ATTACK_EFFORT"], hit: ["HIT_REACT"], taunt: ["TAUNT"], sfx: ["SFX"],
}
const COOLDOWN = { hit: 30, attack: 45, special: 24, taunt: 90, transform: 0, sfx: 0, intro: 0, win: 0, lose: 0, lowHealth: 0 }
const HUMAN_FALLBACK = new Set(["intro", "win", "lose"])

// The deterministic clock: game.js stamps (match seed, sim frame) once per sim frame so combat.js call sites need no frame
// plumbing. Render-side module state, never GAME_STATE.
let _seed = 1, _frame = 0
export function setBen10VoClock(seed, frame) { _seed = (seed >>> 0) || 1; _frame = frame | 0 }
function seedFrame(seed, frame) { return (((seed >>> 0) ^ Math.imul((frame | 0), 0x9e3779b1)) >>> 0) }   // = homelander hlSeedFrame
function playerOf(f) { return ({ p1: 0, p2: 1, p3: 2, p4: 3 })[f?.side] ?? (f?.playerIndex | 0) }

function humanOwner(f) {
  const k = String(f?.rosterKey || "").toLowerCase()
  if (k === "albedo") return "albedo"
  if (k !== "ben10") return null
  return f._benVariant === "classic" ? "ben10:classic" : f._benVariant === "prime" ? null : "ben10:alienforce"
}
// the pool owner speaking for this fighter right now (null = silent)
export function ben10VoOwner(f) {
  const k = String(f?.rosterKey || "").toLowerCase()
  if (k === "vilgax") return "vilgax"
  if (k !== "ben10" && k !== "albedo") return null
  if (f.transformed && f.activeAlien) return BEN10_VO[f.activeAlien] ? f.activeAlien : null   // legacy twins have no pools → silent
  return humanOwner(f)
}
// pure pick (no playback): { owner, pool, clip } or null. Same (seed, frame, player) → same clip.
export function pickBen10Vo(event, f, seed = _seed, frame = _frame, owner0 = null) {
  const owners = [owner0 || ben10VoOwner(f)]
  if (HUMAN_FALLBACK.has(event) && f?.transformed) owners.push(humanOwner(f))
  for (const owner of owners) {
    const P = owner && BEN10_VO[owner]; if (!P) continue
    for (const pool of BEN10_VO_EVENTS[event] || []) {
      const ids = P[pool]
      if (ids && ids.length) return { owner, pool, clip: juicePickVariant(ids, seedFrame(seed, frame), playerOf(f)) }
    }
  }
  return null
}
const _cd = new WeakMap()
// play: returns true if a clip started. ctx = { seed, frame } overrides the stamped clock.
export function playBen10Vo(event, f, ctx = {}) {
  if (!f || !sound?.playSfxFile) return false
  const seed = ctx.seed != null ? (ctx.seed >>> 0) : _seed, frame = ctx.frame != null ? (ctx.frame | 0) : _frame
  const cd = COOLDOWN[event] ?? 0
  if (cd > 0) { let m = _cd.get(f); if (!m) _cd.set(f, (m = {})); if ((frame - (m[event] ?? -1e9)) < cd && frame >= (m[event] ?? -1e9)) return false; m[event] = frame }
  const pick = pickBen10Vo(event, f, seed, frame, ctx.owner || null)
  if (!pick) return false
  const isSfx = BEN10_VO_SFX_POOLS.has(pick.pool)
  const rate = juicePitch(seedFrame(seed, frame), playerOf(f), isSfx ? 0.05 : 0.03)
  try {
    if (isSfx) sound.playSfxFile(pick.clip, null, { rate })
    else sound.playSfxFile(pick.clip, null, { rate, owner: f, fadeMs: 40 })
  } catch (_) { return false }
  return true
}
// game.js ben10Sfx event ids → VO: a transform / swap gets the form's callout + a layered SFX; a form special id gets a callout.
const TRANSFORM_IDS = new Set(["ben_transform", "ben_swap", "ben_vowpick"])
const SILENT_IDS = new Set(["ben_revert", "ben_timeout", "sf_regrow"])
export function ben10VoForSfxEvent(f, id, ctx = {}) {
  if (!f || !id || SILENT_IDS.has(id)) return false
  if (TRANSFORM_IDS.has(id)) {
    // a human → alien transform cues during the startup flash, before the alien is applied: speak as the PENDING alien
    const o = f.omnitrix, pend = (o && (o.startup | 0) > 0 && o.pendingSlot != null) ? o.aliens?.[o.pendingSlot] : null
    const c = (pend && BEN10_VO[pend]) ? { ...ctx, owner: pend } : ctx
    playBen10Vo("sfx", f, c); return playBen10Vo("transform", f, c)
  }
  return playBen10Vo("special", f, ctx)
}
