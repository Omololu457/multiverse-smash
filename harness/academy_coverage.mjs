// harness/academy_coverage.mjs — CHARACTER ACADEMY Phase 3 LIVE FIRE CHECK (long-running). For every fireable
// lesson of every roster fighter, it runs the SHOW ME demo through the REAL input pipeline and checks the move
// ACTUALLY FIRED (read-only detection latched during the demo). It does NOT block on failures: a move that never
// fires is reported as a LIKELY BUG in that fighter (not fixed here). Writes ACADEMY_FIRE_FAILURES.md.
//
// Usage: node harness/academy_coverage.mjs            → ALL fighters (long; CI)
//        node harness/academy_coverage.mjs 20         → first 20 fighters (quick sample)
//        node harness/academy_coverage.mjs naruto,gaara,madara   → specific fighters
import { chromium } from "playwright";
import http from "node:http"; import fs from "node:fs"; import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.dirname(fileURLToPath(import.meta.url)).replace(/\/harness$/, "");
const MIME = { ".html":"text/html",".js":"text/javascript",".mjs":"text/javascript",".css":"text/css",".png":"image/png",".json":"application/json",".m4a":"audio/mp4",".mp3":"audio/mpeg",".jpg":"image/jpeg",".heic":"image/heic",".svg":"image/svg+xml",".woff":"font/woff",".woff2":"font/woff2",".ttf":"font/ttf" };
const server = await new Promise(r => { const s = http.createServer((req, res) => { const u = decodeURIComponent(req.url.split("?")[0]); const f = path.join(ROOT, u === "/" ? "/index.html" : u); if (!f.startsWith(ROOT)) { res.writeHead(403).end(); return; } fs.readFile(f, (e, d) => { if (e) { res.writeHead(404).end(); return; } res.writeHead(200, { "content-type": MIME[path.extname(f)] || "application/octet-stream" }); res.end(d); }); }); s.listen(0, "127.0.0.1", () => r(s)); });
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true, args: ["--autoplay-policy=no-user-gesture-required", "--disable-background-timer-throttling"] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
let PERR = 0;
page.on("pageerror", e => { if (!/drawSasukeAdultStance/.test(e.message)) PERR++; });
const state = () => page.evaluate(() => window.__harness.state());
async function waitFrames(n) { const s = (await state()).frame; await page.waitForFunction(([a, b]) => window.__harness.state().frame >= a + b, [s, n], { timeout: 20000, polling: 16 }).catch(() => {}); }
await page.goto(`${base}/index.html?harness=1`, { waitUntil: "load" });
await page.waitForFunction(() => window.__harness && window.__harness.academy, { timeout: 15000 });

// scope
const arg = process.argv[2];
let roster = await page.evaluate(() => window.__harness.academy.roster());
if (arg && /^\d+$/.test(arg)) roster = roster.slice(0, +arg);
else if (arg) roster = arg.split(",").map(s => s.trim()).filter(Boolean);
console.log(`\n══ ACADEMY FIRE CHECK — ${roster.length} fighter(s) ══`);

const failures = [];   // { key, name, move, cat, input }
let tested = 0, fired = 0;
const t0 = Date.now();
for (const key of roster) {
  const lessons = await page.evaluate(k => window.__harness.academy.lessons(k), key);
  const fireable = lessons.filter(l => l.cat !== "passive");
  let f = 0;
  for (const l of fireable) {
    const d = await page.evaluate(([k, i]) => { window.__harness.academy.openChar(k); return window.__harness.academy.drill(i, "showme"); }, [key, l.i]);
    if (!d) continue;
    await waitFrames((d.scriptLen || 24) + 14);
    const didFire = await page.evaluate(() => window.__harness.academy.fired());
    tested++; if (didFire) { fired++; f++; } else failures.push({ key, move: l.name, cat: l.cat, input: l.input });
    await page.evaluate(() => window.__harness.academy.exit());
    await waitFrames(2);
  }
  const bad = fireable.length - f;
  console.log(`  ${key.padEnd(20)} ${f}/${fireable.length} fired${bad ? `  ⚠ ${bad} did not fire` : ""}`);
}
const secs = Math.round((Date.now() - t0) / 1000);

// report
let md = `# Character Academy — Live Fire Check\n\n_Auto-generated by harness/academy_coverage.mjs. Each fireable move's SHOW ME was run through the real input pipeline; a move that never fired is a LIKELY BUG in that fighter (not fixed here)._\n\n`;
md += `- Scope: ${roster.length} fighter(s)\n- Moves tested: **${tested}**\n- Fired: **${fired}**\n- Did NOT fire (likely bugs): **${failures.length}**\n- Runtime: ${secs}s\n\n`;
md += `## Moves that did NOT fire (likely fighter bugs — investigate separately)\n\n`;
if (!failures.length) md += `_None — every tested move fired._\n`;
else { md += `| Fighter | Move | Category | Input |\n|---|---|---|---|\n`; for (const f of failures) md += `| ${f.key} | ${f.move} | ${f.cat} | ${f.input} |\n`; }
fs.writeFileSync(path.join(ROOT, "ACADEMY_FIRE_FAILURES.md"), md);

console.log(`\n  tested ${tested} · fired ${fired} · did-not-fire ${failures.length} · ${secs}s · pageerrors ${PERR}`);
console.log(`  wrote ACADEMY_FIRE_FAILURES.md`);
console.log(`\n${failures.length === 0 ? "✅" : "⚠ "}  Fire check complete (non-blocking — failures are reported, not fatal)`);
await browser.close(); server.close();
process.exit(0);   // NEVER blocks — failures are a report, not a test failure
