// harness/academy_coverage_report.mjs — CHARACTER ACADEMY Phase 3 COVERAGE REPORT (static analysis, fast).
// Boots the game, asks the Academy for its per-fighter coverage (lessons generated, fireable count, passive/
// undetectable list, weak-detect moves, and moves whose prose implies a scenario tag they're missing), and writes
// ACADEMY_COVERAGE.md. Read-only: it never runs a match. Pair with test:academy-coverage (the live fire check).
import { chromium } from "playwright";
import http from "node:http"; import fs from "node:fs"; import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.dirname(fileURLToPath(import.meta.url)).replace(/\/harness$/, "");
const MIME = { ".html":"text/html",".js":"text/javascript",".mjs":"text/javascript",".css":"text/css",".png":"image/png",".json":"application/json",".m4a":"audio/mp4",".mp3":"audio/mpeg",".jpg":"image/jpeg",".heic":"image/heic",".svg":"image/svg+xml",".woff":"font/woff",".woff2":"font/woff2",".ttf":"font/ttf" };
const server = await new Promise(r => { const s = http.createServer((req, res) => { const u = decodeURIComponent(req.url.split("?")[0]); const f = path.join(ROOT, u === "/" ? "/index.html" : u); if (!f.startsWith(ROOT)) { res.writeHead(403).end(); return; } fs.readFile(f, (e, d) => { if (e) { res.writeHead(404).end(); return; } res.writeHead(200, { "content-type": MIME[path.extname(f)] || "application/octet-stream" }); res.end(d); }); }); s.listen(0, "127.0.0.1", () => r(s)); });
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
await page.goto(`${base}/index.html?harness=1`, { waitUntil: "load" });
await page.waitForFunction(() => window.__harness && window.__harness.academy, { timeout: 15000 });

const rows = await page.evaluate(() => window.__harness.academy.coverage());
const totFighters = rows.length;
const totLessons  = rows.reduce((s, r) => s + r.lessons, 0);
const totFireable = rows.reduce((s, r) => s + r.fireable, 0);
const totPassive  = rows.reduce((s, r) => s + r.passive.length, 0);
const totWeak     = rows.reduce((s, r) => s + r.weak.length, 0);
const totMissing  = rows.reduce((s, r) => s + r.missing.length, 0);

let md = `# Character Academy — Coverage Report\n\n`;
md += `_Auto-generated by harness/academy_coverage_report.mjs (static analysis of getKit + tags; no match run)._\n\n`;
md += `## Totals\n\n`;
md += `- Fighters: **${totFighters}**\n- Lessons generated: **${totLessons}**\n- Fireable (SHOW ME / TRY IT) moves: **${totFireable}**\n`;
md += `- Passive / informational (no drill): **${totPassive}**\n- Weak read-only detection (composite, no obvious signal word): **${totWeak}**\n`;
md += `- Moves whose prose implies a missing scenario tag: **${totMissing}**\n\n`;
md += `Detection legend: **state** (position/airborne/guard) · **move-key** (currentAttack.name) · **grab-state** · **composite** (energy-drop OR cast-pose OR new projectile OR form flag) · **composite-weak** (composite, but no signal word in the prose → verify via test:academy-coverage) · **n/a** (passive).\n\n`;
md += `## Per-fighter\n\n`;
md += `| Fighter | Universe | Lessons | Fireable | Passive | Weak-detect | Missing-tag |\n|---|---|---:|---:|---:|---|---|\n`;
for (const r of rows) {
  md += `| ${r.name} | ${r.universe} | ${r.lessons} | ${r.fireable} | ${r.passive.length} | ${r.weak.join(", ") || "—"} | ${r.missing.map(m => `${m.name} → ${m.want.join("/")}`).join("; ") || "—"} |\n`;
}
md += `\n## Moves flagged WEAK read-only detection (verify with test:academy-coverage)\n\n`;
for (const r of rows) if (r.weak.length) md += `- **${r.name}**: ${r.weak.join(", ")}\n`;
md += `\n## Moves flagged MISSING a scenario tag (candidates for the override map)\n\n`;
for (const r of rows) if (r.missing.length) md += `- **${r.name}**: ${r.missing.map(m => `${m.name} (wants ${m.want.join("/")})`).join("; ")}\n`;
md += `\n_Note: "missing-tag" is a prose heuristic — a hint to curate, not a defect. "Weak-detect" moves still fire; they just lack an obvious keyword, so the live fire check (test:academy-coverage) is the source of truth for whether a move actually fires._\n`;

fs.writeFileSync(path.join(ROOT, "ACADEMY_COVERAGE.md"), md);
console.log(`Coverage: ${totFighters} fighters · ${totLessons} lessons · ${totFireable} fireable · ${totPassive} passive · ${totWeak} weak-detect · ${totMissing} missing-tag`);
console.log(`Wrote ACADEMY_COVERAGE.md`);
await browser.close(); server.close();
process.exit(0);
