// mmprSquadSkins.js — Mighty Morphin Rangers skins (cosmetic only; registers into skins.js SKINS.mmpr_rangers at load).
//   • START AS — which Ranger opens every round (default = Red). The dial still reaches all five.
//   • SQUAD THEMES — one look for the whole squad, following every ↓↓ swap (squadCore applyForm → the hook below).
//     Per Ranger: the gap sheets made by tools/spd_squad/build_squad_skins.py (assets/mmpr_rangers/skins/<theme>/<form>/)
//     → that Ranger's OWN pack for the theme. Pack combos keep the pack's _recolorTag (each kit's FX finds its themed FX
//     by it); gap combos use the default FX (tag null).
import { SKINS } from './skins.js'
import { MMPR_SQUAD } from './mmprSquad.js'

const PORTRAIT = './assets/mmpr_rangers/portrait.png'
const base = { unlockLevel: 0, spriteScale: null, animationData: null }
const list = SKINS.mmpr_rangers || (SKINS.mmpr_rangers = [])
const add = e => { if (!list.some(s => s.id === e.id)) list.push(e) }
const START = [['red', 'Red (Jason)'], ['black', 'Black (Adam)'], ['pink', 'Pink (Kimberly)'], ['green', 'Green (Tommy)'], ['white', 'White (Tommy)']]
for (const [c, who] of START) add({ ...base, id: c === 'red' ? 'default' : `mmpr_rangers_start_${c}`, name: `Start as: ${who}`, portrait: PORTRAIT })

// theme → [skin id, name]; the Alien X id ends "AlienX" so the shared starfield overlay draws over the void suits
export const MMPR_THEME_IDS = {
  alienx: ['mmpr_rangersAlienX', 'Squad: Alien X'], edo: ['mmpr_rangers_squad_edo', 'Squad: Edo Tensei'], heatblast: ['mmpr_rangers_squad_heatblast', 'Squad: Heatblast'],
  upgrade: ['mmpr_rangers_squad_upgrade', 'Squad: Upgrade'], diamondhead: ['mmpr_rangers_squad_diamondhead', 'Squad: Diamondhead'], ghostfreak: ['mmpr_rangers_squad_ghostfreak', 'Squad: Ghostfreak'],
}
// (form × theme) gaps generated by `tools/spd_squad/build_squad_skins.py . mmpr` (Black / Pink / White have all six already)
export const MMPR_GENERATED = { alienx: ['green_ranger'], heatblast: ['red_ranger_mmpr'], upgrade: ['red_ranger_mmpr', 'green_ranger'],
  diamondhead: ['red_ranger_mmpr', 'green_ranger'], ghostfreak: ['red_ranger_mmpr', 'green_ranger'] }
const THEME_OF = () => Object.fromEntries(Object.entries(MMPR_THEME_IDS).map(([t, [id]]) => [id, t]))
for (const [t, [id, name]] of Object.entries(MMPR_THEME_IDS)) add({ ...base, id, name, portrait: `./assets/mmpr_rangers/portrait__${t}.png`, squadTheme: t })

const remap = (anim, fn) => Object.fromEntries(Object.entries(anim).map(([k, a]) => [k, a && a.sheet ? { ...a, sheet: fn(a.sheet) } : a]))
const sheetHas = (anim, t) => { const s = anim?.idle?.sheet || ''; return s.includes(`__${t}.`) || s.includes(`/skins/${t}/`) }
const cache = {}
export function mmprThemeAnim(form, t) {
  const key = form + '|' + t; if (key in cache) return cache[key]
  const c = MMPR_SQUAD.formChar(form); let r = null
  if (c && MMPR_GENERATED[t]?.includes(form)) r = { anim: remap(c.animationData, p => `./assets/mmpr_rangers/skins/${t}/${form}/${p.split('/').pop()}`), tag: null }
  else {
    const e = (SKINS[form] || []).find(s => s.animationData && (s.recolorTag === t || sheetHas(s.animationData, t)))
    if (e) r = { anim: e.animationData, tag: e.recolorTag || null }
  }
  if (r) cache[key] = r   // only hits: a pack that registers later (its Fx module) is still found
  return r
}
MMPR_SQUAD.setSkinHook((f, form) => {
  const t = THEME_OF()[f?.skinId]; if (!t) return
  const r = mmprThemeAnim(form, t); if (!r) return
  f._skinAnim = r.anim; f._baseSkinAnim = r.anim; f._recolorTag = r.tag
})
