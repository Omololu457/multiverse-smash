// preloadManifest.js
// Stage 10 — curated registry of projectile / FX / alternate-FORM body sheets that live as inline
// literals inside abilities.js (there is no central registry there). These are the sheets that fault
// to the _FALLBACK box on their FIRST use — worst during ultimates/transforms, exactly when they spawn.
// preloadFighter() already covers a character's base + skin body sheets from characters.animationData;
// THIS covers everything abilities.js spawns that the base walk never sees.
//
// Attributed by sheet-name prefix (see tools/check_fx_manifest.mjs, the drift guard that regenerates
// this list from abilities.js and fails if any spawned .png is unlisted). Over-listing is harmless
// (it just warms a sheet that may go unused); under-listing reintroduces the first-use fault.
//
// NOTE ON CACHING: FX sheets are drawn via ui.js / per-cinematic private image caches, NOT sprite.js's
// _cache. Decoding them here warms the BROWSER HTTP cache so the eventual (separate) Image load resolves
// from cache instead of the network — the pragmatic 90% fix without unifying every FX cache.

