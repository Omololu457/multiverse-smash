// Union of FX sheets for the given roster keys, deduped. Unknown keys contribute nothing.
export function fxSheetsForFighters(...rosterKeys) {
  const out = new Set();
  for (const k of rosterKeys) for (const p of (FX_SHEETS_BY_CHAR[k] || [])) out.add(p);
  return [...out];
}
