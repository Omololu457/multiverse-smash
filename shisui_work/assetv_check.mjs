import { chromium } from "playwright";
import http from "node:http"; import fs from "node:fs"; import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT=path.dirname(fileURLToPath(import.meta.url)).replace(/\/shisui_work$/,"");
const MIME={".html":"text/html",".js":"text/javascript",".mjs":"text/javascript",".png":"image/png",".json":"application/json",".m4a":"audio/mp4",".mp3":"audio/mpeg"};
const reqs=[];
const server=await new Promise(r=>{const s=http.createServer((rq,rs)=>{const u=decodeURIComponent(rq.url.split("?")[0]);if(u.endsWith(".png"))reqs.push(rq.url);const f=path.join(ROOT,u==="/"?"/index.html":u);if(!f.startsWith(ROOT)){rs.writeHead(403).end();return;}fs.readFile(f,(e,d)=>{if(e){rs.writeHead(404).end();return;}rs.writeHead(200,{"content-type":MIME[path.extname(f)]||"application/octet-stream"});rs.end(d);});});s.listen(0,"127.0.0.1",()=>r(s));});
const base=`http://127.0.0.1:${server.address().port}`;
const br=await chromium.launch({headless:true,args:["--autoplay-policy=no-user-gesture-required"]});
const pg=await br.newPage({viewport:{width:1280,height:720}}); let perr=0; pg.on("pageerror",()=>perr++);
await pg.goto(`${base}/index.html?harness=1&p1=shisui_blade&p2=naruto`,{waitUntil:"load"});
await pg.waitForFunction(()=>window.__harness&&window.__harness.state);
await pg.evaluate(()=>{window.__harness.start?.();window.__harness.skipToBattle?.();});
const av=await pg.evaluate(()=>window.__ASSET_V||null);
await new Promise(r=>setTimeout(r,800));
const sheetReqs=reqs.filter(u=>u.includes("shisui_blade"));
console.log("window.__ASSET_V =", av);
console.log("sample shisui sheet request:", sheetReqs[0]||"(none yet)");
console.log("all shisui sheet reqs have ?v=:", sheetReqs.length>0 && sheetReqs.every(u=>u.includes("?v=")));
console.log("pageErrors:", perr);
await br.close(); server.close();
