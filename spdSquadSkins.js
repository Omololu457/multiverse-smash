// spdSquadSkins.js — S.P.D. Rangers skins (cosmetic only; registers into skins.js SKINS.spd_rangers at load).
//   • START AS — which Ranger opens every round (default = Red). The dial still reaches all six.
//   • SQUAD THEMES — one look for the WHOLE squad: every Ranger wears the theme and it follows each ↓↓ swap
//     (spdSquad.js applyForm → the hook below swaps in that Ranger's themed sheets). Per Ranger, in order:
//       1. the gap sheets made by tools/spd_squad/build_squad_skins.py   (assets/spd_rangers/skins/<theme>/<form>/)
//       2. that Ranger's OWN pack for the theme (Blue/Green/Pink/Yellow inspired packs, Red's spdRedSkins, Omega's set)
//       3. Omega's on-disk recolours (<sheet>__<theme>.png) where no skin entry lists them
//     Pack combos keep the pack's _recolorTag (each Ranger's FX layer finds its themed FX by it); gap combos use the
//     default FX (tag null) because no themed FX files exist for them.
import { SKINS } from './skins.js'
import { spd_rangers, setSquadSkinHook, squadFormChar } from './spdSquad.js'

const PORTRAIT = './assets/spd_rangers/portrait.png'
const base = { unlockLevel: 0, spriteScale: spd_rangers.spriteScale, animationData: null }
const list = SKINS.spd_rangers || (SKINS.spd_rangers = [])
const add = e => { if (!list.some(s => s.id === e.id)) list.push(e) }

const START = [['red', 'Red (Jack)'], ['blue', 'Blue (Sky)'], ['green', 'Green (Bridge)'], ['yellow', 'Yellow (Z)'], ['pink', 'Pink (Syd)'], ['omega', 'Omega (Sam)']]
for (const [c, who] of START) add({ ...base, id: c === 'red' ? 'default' : `spd_rangers_start_${c}`, name: `Start as: ${who}`, portrait: PORTRAIT })

// theme → [skin id, name]; the Alien X id ends "AlienX" so the shared starfield overlay draws over the void suits
export const SQUAD_THEME_IDS = {
  alienx: ['spd_rangersAlienX', 'Squad: Alien X'], edo: ['spd_rangers_squad_edo', 'Squad: Edo Tensei'], shadow: ['spd_rangers_squad_shadow', 'Squad: Shadow'],
  heatblast: ['spd_rangers_squad_heatblast', 'Squad: Heatblast'], diamondhead: ['spd_rangers_squad_diamondhead', 'Squad: Diamondhead'], upgrade: ['spd_rangers_squad_upgrade', 'Squad: Upgrade'],
}
// (form × theme) sheets generated by tools/spd_squad/build_squad_skins.py (GAPS there)
const GENERATED = { heatblast: ['spd_red', 'omega_ranger'], diamondhead: ['spd_red', 'omega_ranger'], upgrade: ['spd_red', 'omega_ranger'], shadow: ['spd_yellow'] }
const THEME_OF = Object.fromEntries(Object.entries(SQUAD_THEME_IDS).map(([t, [id]]) => [id, t]))
for (const [t, [id, name]] of Object.entries(SQUAD_THEME_IDS)) add({ ...base, id, name, portrait: `./assets/spd_rangers/portrait__${t}.png`, squadTheme: t })

const remap = (anim, fn) => Object.fromEntries(Object.entries(anim).map(([k, a]) => [k, a && a.sheet ? { ...a, sheet: fn(a.sheet) } : a]))
const sheetHas = (anim, t) => { const s = anim?.idle?.sheet || ''; return s.includes(`__${t}.`) || s.includes(`/skins/${t}/`) }
const cache = {}
export function squadThemeAnim(form, t) {
  const key = form + '|' + t; if (key in cache) return cache[key]
  const c = squadFormChar(form); let r = null
  if (c && GENERATED[t]?.includes(form)) r = { anim: remap(c.animationData, p => `./assets/spd_rangers/skins/${t}/${form}/${p.split('/').pop()}`), tag: null }
  else {
    const e = (SKINS[form] || []).find(s => s.animationData && (s.recolorTag === t || sheetHas(s.animationData, t)))
    if (e) r = { anim: e.animationData, tag: e.recolorTag || null }
    else if (c && form === 'omega_ranger') r = { anim: remap(c.animationData, p => p.replace(/\.png$/, `__${t}.png`)), tag: null }
  }
  return (cache[key] = r)
}
setSquadSkinHook((f, form) => {
  const t = THEME_OF[f?.skinId]; if (!t) return
  const r = squadThemeAnim(form, t); if (!r) return
  f._skinAnim = r.anim; f._baseSkinAnim = r.anim; f._recolorTag = r.tag
})
