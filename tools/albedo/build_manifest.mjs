// Builds albedoThemeManifest.js: every Albedo-owned __albedo body strip → its form key, plus each form's per-rule
// reference brightness (vref = 90th-percentile HSV value of the pixels that rule matches, over ALL that form's strips).
// Reads Albedo's sheets only (…__albedo.png). Deterministic.   USAGE: node tools/albedo/build_manifest.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { decodePNG } from './png.mjs'
import { ALBEDO_REGIONS, ALBEDO_FORM_KEYS } from '../../albedoThemeRegions.js'
import { classifyAlbedoPixel } from '../../albedoThemeRecolor.js'
import { characters } from '../../characters.js'
import { getSkinAnimationData } from '../../skins.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
// form key → the module whose files list its strips (same table as tools/ben10/gen_albedo_ready.py RULES)
export const FORM_MODULE = { swampfire: 'swampfire', heatblast: 'heatblast', megawhatt: 'megawhatt', goop: 'goop', xlr8: 'xlr8', eyeguy: 'eyeguy',
  ghostfreak: 'ghostfreak', alienx: 'alienx', brainstorm: 'brainstorm', terraspin: 'terraspin', wildvine: 'wildvine', jetray: 'jetray',
  diamondhead_ov: 'diamondhead', upgrade_ov: 'upgrade', humongousaur: 'humongousaur', feedback_ov: 'feedback', arcticguana: 'arcticguana',
  benwolf: 'benwolf', bigchill: 'bigchill', ripjaws: 'ripjaws', rath: 'rath', waterhazard: 'waterhazard', highbreed: 'highbreed', wildmutt_ov: 'wildmutt' }

export function alienStrips(module) {
  const files = new Set([`${module}.js`, ...fs.readdirSync(ROOT).filter(f => f.startsWith(module) && /Assets.*\.js$/.test(f))])
  const out = new Set()
  for (const f of files) {
    const p = path.join(ROOT, f); if (!fs.existsSync(p)) continue
    for (const m of fs.readFileSync(p, 'utf8').matchAll(/(ben10_[A-Za-z0-9_]+_uniform\.png)/g)) out.add(m[1])
  }
  return [...out].filter(s => !s.includes('__') && fs.existsSync(path.join(ROOT, s))).sort().map(s => s.replace(/\.png$/, '__albedo.png'))
}
const sheetsOf = anim => [...new Set(Object.values(anim || {}).map(d => d?.sheet).filter(Boolean).map(s => s.replace(/^\.\//, '')))].sort()

export function stripLists() {
  const L = { older: sheetsOf(characters.albedo.animationData), kid: sheetsOf(getSkinAnimationData('albedo', 'ben10Classic')) }
  for (const k of ALBEDO_FORM_KEYS) L[k] = alienStrips(FORM_MODULE[k])
  return L
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const L = stripLists(), strips = {}, vref = {}, stats = {}
  for (const [form, list] of Object.entries(L)) {
    const nR = ALBEDO_REGIONS[form].rules.length, hist = Array.from({ length: nR }, () => new Float64Array(256))
    for (const s of list) {
      if (!fs.existsSync(path.join(ROOT, s))) throw new Error(`missing Albedo strip ${s}`)
      if (strips[s] && strips[s] !== form) throw new Error(`strip ${s} claimed by ${strips[s]} and ${form}`)
      strips[s] = form
      const { data } = decodePNG(path.join(ROOT, s)), memo = new Map()
      for (let i = 0; i < data.length; i += 4) {
        if (!data[i + 3]) continue
        const key = (data[i] << 16) | (data[i + 1] << 8) | data[i + 2]
        let k = memo.get(key); if (k === undefined) memo.set(key, k = classifyAlbedoPixel(form, data[i], data[i + 1], data[i + 2]))
        if (k >= 0) hist[k][Math.max(data[i], data[i + 1], data[i + 2])]++
      }
    }
    vref[form] = hist.map(hh => { const tot = hh.reduce((a, b) => a + b, 0); if (!tot) return 0; let acc = 0; for (let v = 0; v < 256; v++) { acc += hh[v]; if (acc >= tot * 0.9) return +(v / 255).toFixed(3) } return 1 })
    stats[form] = { strips: list.length, px: hist.map(hh => hh.reduce((a, b) => a + b, 0)) }
  }
  const src = `// GENERATED by tools/albedo/build_manifest.mjs — do not edit by hand. Albedo-only.\n` +
    `// strips: every Albedo-owned __albedo body strip → the form whose region rules recolor it (human: older / kid).\n` +
    `// vref:   per form, per region rule, the reference brightness (90th-percentile HSV value over all that form's strips).\n` +
    `// stats:  per form, strips and matched pixels per rule (docs only).\n` +
    `export const ALBEDO_THEME_MANIFEST = ${JSON.stringify({ strips, vref, stats })}\n`
  fs.writeFileSync(path.join(ROOT, 'albedoThemeManifest.js'), src)
  console.log(Object.entries(stats).map(([f, s]) => `${f.padEnd(15)} ${String(s.strips).padStart(3)} strips  rules px ${s.px.join(' ')}`).join('\n'))
  console.log('total strips', Object.keys(strips).length)
}
