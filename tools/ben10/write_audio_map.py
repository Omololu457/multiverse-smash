#!/usr/bin/env python3
"""write_audio_map.py: docs/ben10/AUDIO_MAP.md from docs/ben10/AUDIO_ANALYSIS.json (written by classify_vo.py). Deterministic."""
import os, json, re
from collections import Counter, OrderedDict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
A = json.load(open(os.path.join(ROOT, "docs/ben10/AUDIO_ANALYSIS.json")))

def legacy(path, name):
    src = open(os.path.join(ROOT, path)).read()
    body = src[src.index(f"export const {name}"):]
    out = {}
    for m in re.finditer(r"(\w+): \[(.*?)\]", body, re.S):
        out[m.group(1)] = re.findall(r'"([^"]+)"\s*,?\s*//\s*(.*)', m.group(2))
    return out

SECTIONS = OrderedDict([
  ("Ben 10 — Alien Force human (default variant) · `ben10:alienforce`", ["ben_teen"]),
  ("Ben 10 — Classic human · `ben10:classic`", ["ben_young"]),
  ("Ben 10 — Prime human · (none)", []),
  ("Albedo — human · `albedo`", ["albedo"]),
  ("Ghostfreak · `ghostfreak`", ["ghostfreak_young", "ghostfreak_teen"]),
  ("Heatblast · `heatblast`", ["heatblast_young"]),
  ("Wildvine · `wildvine`", ["wildvine_young"]),
  ("Big Chill · `bigchill`", ["bigchill"]),
  ("Diamondhead (READY) · `diamondhead_ov`", ["diamondhead"]),
  ("Feedback (READY) · `feedback_ov`", ["feedback"]),
  ("Humongousaur · `humongousaur`", ["humongousaur"]),
  ("Rath · `rath`", ["rath"]),
  ("Swampfire · `swampfire`", ["swampfire"]),
  ("Upgrade (READY) · `upgrade_ov`", ["upgrade"]),
  ("XLR8 · `xlr8`", ["xlr8"]),
  ("Vilgax · `vilgax`", ["vilgax"]),
  ("Kevin 11 · not wired (`assets/audio/_unassigned/kevin11/`)", ["kevin11"]),
])

def summary_row(recs):
    c = Counter(r["pool"] or "—skipped" for r in recs)
    return ", ".join(f"{k} {v}" for k, v in sorted(c.items()))

L = ["# Ben 10 cast — voice-over map", "",
     "Generated by `tools/ben10/write_audio_map.py` from `docs/ben10/AUDIO_ANALYSIS.json` (`tools/ben10/classify_vo.py`). "
     "Every clip was sorted by **waveform shape only** (ffprobe duration; peak / RMS; zero-crossing rate; spectral centroid; "
     "voiced-energy ratio; silence ratio; loudness slope). **Nobody listened to these clips and no clip was transcribed**, so "
     "every pool assignment is a shape guess for a human to spot-check.", "",
     "## Phase 0 findings", "",
     "- **Vilgax**: a roster character (`characters.vilgax`, universe `ben_10`, sprite-backed). He already had a thin, "
     "transcript-verified pack (`vilgaxVoice.js`: 1 taunt + 2 grunts). The owner chose to **copy and wire** the 23 new clips "
     "(`assets/audio/vilgax/source/`). His old clips are merged into the matching pools, and his voice now uses the same "
     "deterministic dispatch.",
     "- **Kevin 11**: no Kevin 11 character exists on committed `main`. (A separate `kevin_levin` character is being built in "
     "another session's uncommitted work.) The 41 `kevin11` clips are copied to `assets/audio/_unassigned/kevin11/` and are "
     "**not wired**, per the brief. They can be routed to that character once it lands.",
     "- **READY twins**: every clip goes to the READY alien key, never the legacy experimental twin: diamondhead → "
     "`diamondhead_ov`, feedback → `feedback_ov`, upgrade → `upgrade_ov`. The legacy twins have no pools and stay silent.",
     "- **No READY alien had VO before**: only Ben 10's procedural WebAudio synth (`sound.playBen10`). That synth is unchanged.", "",
     "## Mechanism (reused, not new)", "",
     "`ben10VoiceMap.js` copies the `homelander_sfx_map.js` dispatch:",
     "- The clip is `juicePickVariant(hash(match seed, frame), player)`.",
     "- Pitch is ±3% for voice and ±5% for SFX (`juicePitch`).",
     "- Per-event cooldowns: hit 30f, attack 45f, special 24f, taunt 90f; intro, win, lose and transform always play.",
     "- Voice uses `playSfxFile({ owner, fadeMs: 40 })`: one voice per character, a 40 ms crossfade, and music ducking.",
     "- No random source. Cooldown stamps live in a module WeakMap, never in GAME_STATE.", "",
     "**Triggers:**",
     "- intro: the match intro beat; the select-screen bark is a deterministic pick.",
     "- win / lose: the victory block. A transformed fighter speaks as the alien, then falls back to the human pool.",
     "- transform: the Omnitrix transform / swap / Vow-pick cue plays SPECIAL_CALLOUT (else TAUNT) plus a layered SFX.",
     "- special: a form special's synth cue, or a special / ultimate connect.",
     "- attack: a clean connect. taunt: a long-string connect. hit: taking a hit.",
     "- lowHealth: Albedo only, using his transcript-verified line.", "",
     "**Rules:**",
     "- A clip over 8 s is EXCLUDED as \"unverified, possible music\".",
     "- Near-silent clips are excluded.",
     "- Clips from an UNVERIFIED-era folder can land only in ATTACK_EFFORT / SFX / TAUNT.",
     "- INTRO / WIN / LOSE from verified folders were assigned **by shape** (owner's choice) and are flagged "
     "*wording unverified*.", "",
     "## Summary", "", "| destination | source folders | clips | assigned | excluded (> 8 s possible music) | excluded (near-silent) | pools |",
     "|---|---|---|---|---|---|---|"]
for title, folders in SECTIONS.items():
    recs = [r for f in folders for r in A.get(f, [])]
    if not recs: L.append(f"| {title} | — | 0 | 0 | 0 | 0 | **no clips: pools empty** |"); continue
    ass = sum(1 for r in recs if r["pool"]); mus = sum(1 for r in recs if (r["skipped"] or "").startswith("unverified, possible music"))
    sil = sum(1 for r in recs if r["skipped"] == "near-silent")
    L.append(f"| {title} | {', '.join(folders)} | {len(recs)} | {ass} | {mus} | {sil} | {summary_row([r for r in recs if r['pool']]) or '—'} |")
tot = [r for f in A.values() for r in f]
L += ["", f"Total: {len(tot)} clips copied, {sum(1 for r in tot if r['pool'])} wired, "
      f"{sum(1 for r in tot if (r['skipped'] or '').startswith('unverified, possible music'))} excluded as possible music, "
      f"{sum(1 for r in tot if r['skipped'] == 'near-silent')} near-silent, {len(A.get('kevin11', []))} Kevin 11 (unassigned).", ""]
AL = legacy("albedoVoice.js", "ALBEDO_VOICE"); VG = legacy("vilgaxVoice.js", "VILGAX_VOICE")
for title, folders in SECTIONS.items():
    L += [f"## {title}", ""]
    if not folders:
        L += ["No clips cover the Prime variant: its pools are empty and unassigned, so Prime Ben is silent (the synth cues still play).", ""]
        continue
    for f in folders:
        recs = A.get(f, [])
        if not recs: continue
        ver = recs[0]["verified_era"]
        L += [f"Source folder `{f}`: era {'verified by ear (per the delivery manifest)' if ver else '**⚠ UNVERIFIED**: every clip below is flagged, even when assigned'} · "
              f"dest `{os.path.dirname(recs[0]['path'])[2:]}`", "",
              "| clip | dur s | voiced | vRMS dB | slope dB | pool | flags / skip reason |", "|---|---|---|---|---|---|---|"]
        for r in recs:
            flags = "; ".join(r["flags"] + ([r["skipped"]] if r["skipped"] else []))
            L.append(f"| `{r['file']}` | {r['duration']:.2f} | {r['voiced_ratio']:.2f} | {r['voiced_rms_db']:.1f} | {r['rms_slope_db']:.1f} | "
                     f"{r['pool'] or '—'} | {flags} |")
        L.append("")
    if "albedo" in folders:
        L += ["Merged from the earlier **transcript-verified** Albedo pack (`albedoVoice.js`, `voice/albedo/*.mp3`):", "",
              "| clip | pool | transcript |", "|---|---|---|"]
        for pool, P in (("intro", "INTRO"), ("taunt", "TAUNT"), ("win", "WIN"), ("lowHealth", "LOW_HEALTH")):
            for c, t in AL.get(pool, []): L.append(f"| `{c}` | {P} | {t.strip()} |")
        L.append("")
    if "vilgax" in folders:
        L += ["Merged from the earlier **transcript-verified** Vilgax pack (`vilgaxVoice.js`):", "", "| clip | pool | transcript |", "|---|---|---|"]
        for pool, P in (("taunt", "TAUNT"), ("hitReact", "HIT_REACT")):
            for c, t in VG.get(pool, []): L.append(f"| `{c}` | {P} | {t.strip()} |")
        L.append("")
os.makedirs(os.path.join(ROOT, "docs/ben10"), exist_ok=True)
open(os.path.join(ROOT, "docs/ben10/AUDIO_MAP.md"), "w").write("\n".join(L) + "\n")
print("wrote docs/ben10/AUDIO_MAP.md", len(L), "lines")
