#!/usr/bin/env python3
"""Write creativeSkins.js from tools/creativeskins/manifest.json (+ drop.json): the creative skins each fighter gets and the
flat / broken skins they replace. skins.js imports it."""
import json, os
D = os.path.dirname(__file__); ROOT = os.path.abspath(os.path.join(D, '..', '..'))
man = json.load(open(os.path.join(D, 'manifest.json')))
drop = json.load(open(os.path.join(D, 'drop.json'))) if os.path.exists(os.path.join(D, 'drop.json')) else {}
L = ['// creativeSkins.js — GENERATED by tools/creativeskins/emit.py (do not hand-edit). Creative recolour skins for fighters whose',
     '// skins were missing, broken (sheets deleted) or flat one-colour tints. Each skin is inspired by another fighter; the art is',
     '// `<sheet>__<tag>.png` beside every default sheet (tools/creativeskins/build.py) → same frames / timing / hitboxes.',
     'export const CREATIVE_SKINS = {']
for k in sorted(man):
    L.append(f'  {k}: [' + ', '.join(json.dumps(x, ensure_ascii=False) for x in man[k]) + '],')
L.append('}')
L.append('// Skins these replace: flat whole-body tints (face dyed with the outfit) and skins whose art no longer exists.')
L.append('export const CREATIVE_DROP = {')
for k in sorted(drop):
    if drop[k]: L.append(f'  {k}: ' + json.dumps(drop[k]) + ',')
L.append('}')
open(os.path.join(ROOT, 'creativeSkins.js'), 'w').write('\n'.join(L) + '\n')
print('creativeSkins.js:', sum(len(v) for v in man.values()), 'skins,', sum(len(v) for v in drop.values()), 'dropped')
