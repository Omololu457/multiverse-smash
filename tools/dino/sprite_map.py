"""MSV1-DINO: write docs/msv1/dino/SPRITE_MAP.md from the real ledgers (tools/dino/extract.py) and the pack tables
(tools/dino/pack.py) — every number in it is read, not typed.  Run: python3 tools/dino/sprite_map.py"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE)); sys.path.insert(0, HERE)
import pack
D = os.path.join(ROOT, 'docs', 'msv1', 'dino')
SRC = {'red': 'Red Ranger.gif (falmeatwad)', 'blue': 'Blue Ranger.png (YONDY-HOKAGE / DK-YONDY)', 'yellow': 'Yellow Ranger.png (YONDY-HOKAGE / DK-YONDY)',
       'white': 'White Ranger.png (YONDY-HOKAGE / DK-YONDY)', 'drago': 'Drago Ranger.png (Raikage)'}
OWN = {'dt_red': {'hurt', 'hurtAir', 'down', 'getup', 'lose', 'guard', 'win', 'taunt', 'crouch', 'fall', 'land'},
       'dt_blue': {'crouch', 'fall', 'land', 'guard', 'win', 'taunt'}, 'dt_yellow': {'crouch', 'fall', 'land', 'guard', 'win', 'taunt'},
       'dt_white': {'hurt', 'hurtAir', 'down', 'getup', 'lose', 'guard', 'win', 'taunt', 'crouch', 'fall', 'land', 'jump'}}
L = ['# MSV1-DINO — sprite map', '', 'Generated by `tools/dino/sprite_map.py` from `docs/msv1/dino/ledgers/*.json` (the cut) and `tools/dino/pack.py` (the strips).',
     'Every supplied sheet was cut by its exact background colour into connected components; every component is either used in a',
     'section or listed as excluded with a reason (UNACCOUNTED = none). Cells are MSV1_CELL 260×136 (origin 130,132), so ninja.js /',
     'nsFx.js draw them unchanged. No art was invented or redrawn.', '', '## Real frame counts per sheet', '']
for sheet in ['red', 'blue', 'yellow', 'white', 'drago']:
    led = json.load(open(os.path.join(D, 'ledgers', sheet + '.json')))
    secs = ', '.join(f"{k} {len(v)}" for k, v in led['sections'].items())
    L += [f"- **{SRC[sheet]}** — {led['components']} components; sections: {secs}; excluded {len(led['excluded'])} (labels / credit / example composites / boxes)"]
L += ['', '## Strips per form (anim → sheet:section[frame indices])', '']
for form, T in pack.FORMS.items():
    L += [f'### {form}', '', '| anim | frames | source |', '|---|---|---|']
    for anim, frs in T.items():
        src = '; '.join(f"{s}:{sec}[{i}]" for s, sec, i in frs)
        note = ' *(missing on the sheet — the form\'s own closest frame)*' if anim in OWN.get(form, ()) else ''
        L += [f'| {anim} | {len(frs)} | {src}{note} |']
    L += ['']
L += ['## Trent palette unification', '',
      'The White Ranger sheet (DK-YONDY) and the Drago sheet (Raikage) are one character. Drago\'s 15 body colours are byte-identical to',
      'the White sheet\'s main 15, so `tools/dino/extract.py unify_trent` maps both sheets onto that 15-colour palette: White kept 22441 px,',
      'remapped 33 stray anti-alias pixels to the nearest palette colour, de-haloed 3 key-green blends into alpha; Drago kept 42310,',
      'remapped 10. The painted portrait is left as drawn. Both run heights are 60 px (no scale mismatch).', '',
      '## Extras (assets/dinothunder)', '', ', '.join(sorted(os.path.splitext(f)[0] for f in os.listdir(os.path.join(ROOT, 'assets', 'dinothunder')))), '',
      'Derived (tools/dino/portraits.py): `assets/dt_*/portrait_large|small.png` (the sheet portraits, nearest-neighbour fit), the team',
      'portrait (the four side by side) and `assets/dt_white/clone/*.png` — the DRAGO CLONE: Trent\'s own strips through a fixed',
      'per-colour map (white suit → charcoal, gold → blood red, black kept, alpha untouched). Premade, never recoloured at runtime.']
open(os.path.join(D, 'SPRITE_MAP.md'), 'w').write('\n'.join(L) + '\n')
print('wrote SPRITE_MAP.md', len(L), 'lines')
