# Names that may legitimately survive (shared-by-reference data / art / sound ids / asset paths / prose comments)
ALLOWED = re.compile(r"SYNDROME_(MOVES|PARTS|FX_COLORS|ANIM)|'syndrome_' \+ v|\./assets/syndrome/|syndromeSprites\.js|syndromeSkins\.js|syndromeData\.js|^\s*//|// .*$")


def wb(s, a, b): return re.sub(r'(?<![A-Za-z0-9_$])' + re.escape(a) + r'(?![A-Za-z0-9_$])', b, s)


def build(src, dst, ph):
    s = (ROOT / src).read_text()
    for a, b in IDS: s = wb(s, a, b)
    for a, b in LITERALS: s = s.replace(a, b)
    for p_, a, b in INSERT.get(dst, []):
        if p_ > ph: continue
        n = s.count(a)
        if n != 1: sys.exit(f'{dst}: anchor found {n}x: {a[:70]!r}')
        s = s.replace(a, b)
    s = HEADER.format(src=src) + s
    bad = [ln for ln in s.splitlines() if re.search(r'syndrome', ln, re.I) and not ALLOWED.search(re.sub(r"//.*$", "", ln) or '//')
           and re.search(r'syndrome', re.sub(r"//.*$", "", ln), re.I)]
    bad = [ln for ln in bad if not ALLOWED.search(ln) or re.search(r"rosterKey === 'syndrome'|isSyndrome|_syndrome\b", ln)]
    if bad: sys.exit(f'{dst}: id-bound Syndrome name survived:\n' + '\n'.join(bad[:10]))
    (OUT / dst).write_text(s)
    print('wrote', dst, len(s.splitlines()), 'lines')


PH = int(sys.argv[sys.argv.index('--phase') + 1]) if '--phase' in sys.argv else 99
