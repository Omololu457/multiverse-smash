#!/usr/bin/env python3
"""tools/edoskin/emit_keys.py — write edoSkinKeys.js: the characters that HAVE generated Edo Tensei art (report sheets > 0)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
e = json.load(open(os.path.join(HERE, 'eligibility.json')))
keys = sorted(k for k, c in e['classes'].items() if c in ('HUMAN', 'MASKED') and k not in e.get('exclude', {})
              and os.path.exists(os.path.join(HERE, 'report', k + '.json')) and json.load(open(os.path.join(HERE, 'report', k + '.json')))['sheets'] > 0)
open(os.path.join(ROOT, 'edoSkinKeys.js'), 'w').write(
    "// edoSkinKeys.js — MSV1-EDO (GENERATED by tools/edoskin/emit_keys.py — do not hand-edit).\n"
    "// Characters with premade \"Edo Tensei\" art (<sheet>__edo.png beside every default / form sheet, tools/edoskin/gen.py).\n"
    "// Eligibility + reasons for everyone left out: tools/edoskin/eligibility.json · docs/msv1/edo/LEDGER.md\n"
    "export const EDO_SKIN_KEYS = Object.freeze([\n" + ''.join(f'  "{k}",\n' for k in keys) + "])\n")
print(len(keys))
