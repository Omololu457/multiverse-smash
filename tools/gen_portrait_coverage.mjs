// tools/gen_portrait_coverage.mjs
// Generates portrait_coverage.md — one row per roster key with the THEMED-HUD
// portrait SOURCE (select art / idle crop / fallback), the auto-derived accent
// colour, and the character's form count. Run: node tools/gen_portrait_coverage.mjs
import { existsSync } from "node:fs"
import { writeFileSync } from "node:fs"
import { characters } from "../characters.js"
import { getHudAccentByKey } from "../hud_theme.js"

const rows = []
const counts = { select: 0, idle: 0, fallback: 0 }
const fallbacks = []

for (const [key, ch] of Object.entries(characters)) {
  if (!ch || typeof ch !== "object" || !ch.rosterKey) continue
  const explicit = ch.portrait
  const conv = `./${key}_portrait.png`
  const hasSelect = !!(explicit && existsSync(explicit.replace(/^\.\//, ""))) || existsSync(conv.replace(/^\.\//, ""))
  const hasIdle = !!(ch.animationData && ch.animationData.idle && ch.animationData.idle.width)
  let source
  if (hasSelect) { source = "select art"; counts.select++ }
  else if (hasIdle) { source = "idle crop"; counts.idle++ }
  else { source = "FALLBACK"; counts.fallback++; fallbacks.push(key) }
  const accent = getHudAccentByKey(key)
  const forms = ch.transformations ? Object.keys(ch.transformations).length : 0
  rows.push({ key, name: ch.name || key, universe: ch.universe || "?", source, accent, forms })
}

rows.sort((a, b) => a.key.localeCompare(b.key))

let md = `# Themed HUD — Portrait & Accent Coverage\n\n`
md += `Generated by \`tools/gen_portrait_coverage.mjs\`. One row per roster key.\n`
md += `Portrait resolution priority (ui.js \`_resolveHudPortrait\`): **override → select/cut-in art → idle head-crop → initial-letter fallback**.\n\n`
md += `- **Total roster keys:** ${rows.length}\n`
md += `- **Select art:** ${counts.select}  ·  **Idle head-crop:** ${counts.idle}  ·  **Fallback (initial letter):** ${counts.fallback}\n\n`
md += `## Fallback characters (no portrait file + no idle frame)\n\n`
md += fallbacks.length ? fallbacks.map(k => `- \`${k}\``).join("\n") + "\n\n" : "_None — every character resolves to select art or an idle crop._\n\n"
md += `## Full table\n\n`
md += `| rosterKey | name | universe | portrait source | accent | forms |\n`
md += `|---|---|---|---|---|---|\n`
for (const r of rows) {
  md += `| \`${r.key}\` | ${r.name} | ${r.universe} | ${r.source} | \`${r.accent}\` | ${r.forms} |\n`
}

writeFileSync(new URL("../portrait_coverage.md", import.meta.url), md)
console.log(`portrait_coverage.md written — ${rows.length} keys · select ${counts.select} · idle ${counts.idle} · fallback ${counts.fallback}`)
