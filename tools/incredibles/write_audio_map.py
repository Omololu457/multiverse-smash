#!/usr/bin/env python3
"""write_audio_map.py: docs/incredibles/AUDIO_MAP.md from docs/incredibles/AUDIO_ANALYSIS.json (run classify_vo.py first).
USAGE: python3 tools/incredibles/write_audio_map.py"""
import os, json

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
A = json.load(open(os.path.join(ROOT, "docs/incredibles/AUDIO_ANALYSIS.json")))
ORDER = ["INTRO", "WIN", "LOSE", "HIT_REACT", "ATTACK_EFFORT", "SPECIAL_CALLOUT", "SFX", "TAUNT"]
EVENTS = [("intro (match start + select bark)", "INTRO → TAUNT"), ("win (victory)", "WIN → TAUNT"), ("lose (victory, the loser)", "LOSE → HIT_REACT"),
          ("special / ultimate connects", "SPECIAL_CALLOUT → ATTACK_EFFORT"), ("normal connects", "ATTACK_EFFORT"),
          ("connect while comboCounter ≥ burst min", "TAUNT"), ("taking a hit", "HIT_REACT")]
total = sum(len(o["clips"]) for o in A.values())
wired = sum(1 for o in A.values() for c in o["clips"] if c["pool"])
L = ["# The Incredibles cast: voice audio map", "",
     "Generated by `tools/incredibles/write_audio_map.py` from `docs/incredibles/AUDIO_ANALYSIS.json` (do not hand-edit).", "",
     "## Skipped characters (Phase 0)", "",
     "**None.** All six delivered folders map to live roster characters on `main`, so every folder was wired and nothing was archived "
     "under `assets/audio/_unassigned/`. Roster keys: `dash_parr` (folder `dash`), `elastigirl`, `frozone`, `mr_incredible`, `syndrome`, `violet`.", "",
     "## How clips were classified", "",
     "Nobody listened to these clips. Each was sorted by **waveform shape only** (ffprobe + 16 kHz decode: duration, peak/RMS, "
     "zero-crossing rate, spectral centroid, voiced-energy ratio, silence ratio, RMS slope). Rules: `tools/incredibles/classify_vo.py` docstring.",
     "",
     "- Clips **over 8 s** are excluded as *unverified, possible music* and are never wired. They are still copied to disk.",
     "- **INTRO / WIN / LOSE** come from 2.6–8 s speech ranked by loudness slope. They are flagged *wording unverified (shape-assigned)*, so spot-check them by ear.",
     "- **SPECIAL_CALLOUT is generic for everyone.** No clip can be confirmed to name a specific move without listening, so there are no per-ability pools.",
     "- **Syndrome (villain)** gets a different split. Any loud 0.9–2.6 s line is a callout, and his long lines go about 15 % WIN, 15 % LOSE, 15 % INTRO and 55 % TAUNT.",
     "",
     f"**Totals:** {total} clips delivered, {wired} wired, {total - wired} skipped.", "",
     "## Dispatch (`incrediblesVoiceMap.js`)", "",
     "Clip = `juicePickVariant(pool, hash(match seed, frame), player index)`, with no `Math.random`. Pitch varies by ±3 % for voice and ±5 % for SFX.",
     "Voice uses the one-voice-per-character channel with a 40 ms crossfade and music ducking. Per-event cooldowns are hit 30f, attack 45f, special 24f and taunt 90f.", "",
     "| game event | pools tried (first non-empty wins) |", "|---|---|"]
L += [f"| {e} | {p} |" for e, p in EVENTS]
L += ["", "## Pool counts", "", "| character | source | " + " | ".join(ORDER) + " | skipped |", "|---|---|" + "---|" * (len(ORDER) + 1)]
for k, o in A.items():
    cnt = {p: sum(1 for c in o["clips"] if c["pool"] == p) for p in ORDER}
    L.append(f"| `{k}` | {o['source_credit']} | " + " | ".join(str(cnt[p]) for p in ORDER) + f" | {sum(1 for c in o['clips'] if not c['pool'])} |")
L += ["", "## Excluded clips (likely music / narration bleed, > 8 s)", ""]
ex = [(k, c) for k, o in A.items() for c in o["clips"] if not c["pool"]]
L += [f"- `{k}` · `{c['file']}` · {c['duration']} s · {c['skipped']}" for k, c in ex] or ["- none"]
for k, o in A.items():
    L += ["", f"## `{k}`: {o['display_name']} ({o['source_credit']})", "",
          f"Source folder `{o['source_folder']}/` → `assets/audio/{k}/source/`. "
          f"Folder medians: voiced RMS {o['folder_medians']['voiced_rms_db']} dB, voiced ratio {o['folder_medians']['voiced_ratio']}."
          + (" **Villain pool balance.**" if o["villain"] else ""), "",
          "| clip | dur (s) | voiced | slope dB | pool | note |", "|---|---|---|---|---|---|"]
    for c in o["clips"]:
        note = c["skipped"] or ", ".join(c["flags"])
        L.append(f"| {c['file']} | {c['duration']} | {c['voiced_ratio']} | {c['rms_slope_db']} | {c['pool'] or '—'} | {note} |")
os.makedirs(os.path.join(ROOT, "docs/incredibles"), exist_ok=True)
open(os.path.join(ROOT, "docs/incredibles/AUDIO_MAP.md"), "w").write("\n".join(L) + "\n")
print("wrote docs/incredibles/AUDIO_MAP.md", total, "clips", wired, "wired")
