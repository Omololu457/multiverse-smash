#!/usr/bin/env python3
"""MSV1 Invincible voice: cut Invincible (Mark Grayson)'s voice clips out of the "Invincible VS Invincible Voice Lines + Efforts"
compilation and write invincibleVoice.js (audio-only pools).

  python3 tools/invinciblevoice/build_vo.py [path/to/source.mp3]      (default: ~/Downloads/<curation.source file>)

tools/invinciblevoice/curation.json holds every chosen clip: its pool, start / duration in the source (silence-detected) and
its transcript (faster-whisper small.en, offline). Lines addressed to a named opponent, two-part lines split across clips,
and garbled efforts are left out (see the README section in curation.json's note). Each clip is loudness-normalised
(EBU R128, -16 LUFS, two-pass-free single loudnorm) to mono 44.1 kHz MP3 → assets/audio/invincible/inv_NNN.mp3.
Re-runnable; deterministic for a given source file.
"""
import json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CUR = json.load(open(os.path.join(os.path.dirname(__file__), 'curation.json')))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Downloads/Invincible VS Invincible Voice Lines + Efforts.mp3')
OUT = os.path.join(ROOT, 'assets', 'audio', 'invincible')
JS = os.path.join(ROOT, 'invincibleVoice.js')

ORDER = ['intro', 'introOmni', 'win', 'notYet', 'super', 'ipunch', 'nhb', 'nhbLast', 'shout', 'bark', 'hurt', 'hurtBig', 'ko', 'effort', 'effortHeavy']
DOC = {
    'intro': 'round-1 intro (lines that work against anyone)', 'introOmni': 'round-1 intro vs Omni-Man (the "Dad. Stop." bubble)',
    'win': 'win quote (first = shown with the "Still standing." bubble)', 'notYet': "Can't Stay Down → RESOLVE",
    'super': 'Terminal Velocity (the ultimate)', 'ipunch': 'Invincible Punch', 'nhb': 'No Holds Barred', 'nhbLast': 'No Holds Barred: the last hit',
    'shout': 'a strong hit lands (cooldown)', 'bark': 'zip / takeoff call-outs', 'hurt': 'he is hit', 'hurtBig': 'a big hit / knockdown / wall crash',
    'ko': 'KO', 'effort': 'light / medium attack grunt', 'effortHeavy': 'heavy attack / Skyward / Crash yell',
}


def main():
    if not os.path.exists(SRC):
        sys.exit(f'source not found: {SRC}')
    os.makedirs(OUT, exist_ok=True)
    clips = {}
    for pool in ORDER:
        for c in CUR['pools'].get(pool, []):
            clips[c['i']] = c
    for i, c in sorted(clips.items()):
        dst = os.path.join(OUT, f'inv_{i:03d}.mp3')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f"{c['start']:.3f}", '-t', f"{c['dur']:.3f}", '-i', SRC,
                        '-af', 'loudnorm=I=-16:TP=-1.5:LRA=11,afade=t=in:d=0.01,areverse,afade=t=in:d=0.03,areverse',
                        '-ac', '1', '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', '80k', dst], check=True)
    lines = ['// Generated by tools/invinciblevoice/build_vo.py — do not hand-edit. Invincible (Mark Grayson) voice pools (AUDIO-ONLY,',
             '// no gameplay effect): clips cut from "Invincible VS Invincible Voice Lines + Efforts" and transcribed offline',
             '// (tools/invinciblevoice/curation.json). Each entry: [file, transcript, seconds].',
             "const D = './assets/audio/invincible/'",
             'export const INV_VOICE = {']
    for pool in ORDER:
        items = CUR['pools'].get(pool, [])
        lines.append(f'  // {DOC[pool]}')
        lines.append(f'  {pool}: [' + ', '.join(json.dumps([f"inv_{c['i']:03d}.mp3", c['text'], round(c['dur'], 2)], ensure_ascii=False) for c in items) + '].map(([f, t, d]) => [D + f, t, d]),')
    lines.append('}')
    open(JS, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    size = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
    print(f'{len(clips)} clips → {OUT} ({size / 1e6:.1f} MB); pools: ' + ', '.join(f'{p} {len(CUR["pools"].get(p, []))}' for p in ORDER))


if __name__ == '__main__':
    main()
