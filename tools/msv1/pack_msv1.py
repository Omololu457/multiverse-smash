#!/usr/bin/env python3
"""MSV1 strip packer: Phase-1 frames (assets/incoming/msv1/frames/{red,yellow}) -> per-animation strips
assets/ns_red/<anim>.png + assets/ns_yellow/<anim>.png + msv1Sprites.js (one shared metadata table).
One frame map (docs/msv1/FRAME_MAP.json + ANIM_MAP.json) applied to BOTH sheets (proven palette swap).
Nearest-neighbour only (no resampling at all: frames are pasted 1:1). Sprites face right.
Anchor: grounded rows -> feet on the row's baseline (authored vertical offsets kept); air rows -> per-frame bottom.
Horizontal anchor = centroid of the torso band (30-60% of the frame height); streak smears -> leading edge.
"""
import json, os, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FM = json.load(open(os.path.join(ROOT, 'docs/msv1/FRAME_MAP.json')))
AM = json.load(open(os.path.join(ROOT, 'docs/msv1/ANIM_MAP.json')))
CW, CH = 260, 136          # uniform body cell (like SPD Red's uniform 160x84)
OX, OY = CW // 2, CH - 4   # feet point inside the cell
AIR_ROWS = {'R8', 'R9', 'R10', 'R18', 'R3'}
FX_CENTER = {'fxSpark', 'beam', 'beamDiag', 'fxBurst', 'hitSpark'}   # FX pieces: centred in the cell
rows = {r['row']: r for r in FM['rows']}

def torso_x(img):
    w, h = img.size; a = img.getchannel('A').load()
    y0, y1 = int(h * 0.30), max(int(h * 0.30) + 1, int(h * 0.60))
    s = n = 0
    for y in range(y0, y1):
        for x in range(w):
            if a[x, y] > 0: s += x; n += 1
    return s / n if n else w / 2

def pack(color, outdir):
    meta = {}
    for e in AM:
        row = rows[e['row']]; base = max(f['y'] + f['h'] for f in row['frames'])
        idx = list(range(e['a'], e['b'] + 1))
        strip = Image.new('RGBA', (CW * len(idx), CH), (0, 0, 0, 0))
        used = []
        for k, i in enumerate(idx):
            fr = row['frames'][i]
            img = Image.open(os.path.join(ROOT, 'assets/incoming/msv1/frames', color, f"{fr['id']}.png")).convert('RGBA')
            w, h = img.size
            if e['anim'] in FX_CENTER:
                px, py = OX - w // 2, CH // 2 - h // 2
            else:
                ax = (w - 24) if e['row'] == 'R3' else torso_x(img)
                bottom_off = 0 if e['row'] in AIR_ROWS else (base - (fr['y'] + fr['h']))
                px, py = int(round(OX - ax)), OY - h - bottom_off
            px = max(0, min(CW - w, px)); py = max(0, min(CH - h, py))
            strip.alpha_composite(img, (k * CW + px, py))
            used.append(fr['id'])
        strip.save(os.path.join(outdir, e['anim'] + '.png'))
        meta[e['anim']] = {'frames': len(idx), 'src': used}
    return meta

if __name__ == '__main__':
    out = {}
    for color, key in (('red', 'ns_red'), ('yellow', 'ns_yellow')):
        d = os.path.join(ROOT, 'assets', key); os.makedirs(d, exist_ok=True)
        out[key] = pack(color, d)
        for p in ('portrait_large', 'portrait_small'):
            Image.open(os.path.join(ROOT, 'assets/incoming/msv1/frames', color, p + '.png')).save(os.path.join(d, p + '.png'))
    assert out['ns_red'].keys() == out['ns_yellow'].keys()
    strips = {k: v['frames'] for k, v in out['ns_red'].items()}
    used = sorted({i for v in out['ns_red'].values() for i in v['src']})
    js = ['// GENERATED by tools/msv1/pack_msv1.py — do not hand-edit. One frame map, two sheets (palette swap, docs/msv1/SPRITE_MAP.md).',
          f'export const MSV1_CELL = {{ width: {CW}, height: {CH}, originX: {OX}, originY: {OY} }}',
          f'export const MSV1_STRIPS = {json.dumps(strips)}',
          f'export const MSV1_SRC = {json.dumps({k: v["src"] for k, v in out["ns_red"].items()})}',
          f'export const MSV1_FRAMES_USED = {len(used)}']
    open(os.path.join(ROOT, 'msv1Sprites.js'), 'w').write('\n'.join(js) + '\n')
    print('strips', len(strips), 'frames used', len(used))

# ── FX strips (tight cells) for projectiles / sparks, cut from frames already in the map (no invented art) ──
FX_SRC = {'proj_spark': ['R21_00'], 'proj_beam': ['R21_01', 'R21_02', 'R21_03'], 'proj_beamDiag': ['R21_04', 'R21_05', 'R21_06'],
          'proj_burst': ['R21_07', 'R21_08', 'R21_09', 'R21_10'], 'fx_hitSpark': ['R11_11']}

def crescent_mask():
    """GALE CRESCENT: the detached white/gold arc of R15_03 (the arc in front of the blade). Mask computed on the
    red sheet (crescent = not suit-red, right of the hand, largest connected component) and applied to both sheets
    (identical alpha masks: palette-swap proof)."""
    im = Image.open(os.path.join(ROOT, 'assets/incoming/msv1/frames/red/R15_03.png')).convert('RGBA'); w, h = im.size; px = im.load()
    cand = {(x, y) for x in range(38, w) for y in range(h) if px[x, y][3] > 0 and not (px[x, y][0] > 120 and px[x, y][1] < 90)}
    seen, best = set(), []
    for p in cand:
        if p in seen: continue
        comp, st = [], [p]; seen.add(p)
        while st:
            q = st.pop(); comp.append(q)
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    r = (q[0] + dx, q[1] + dy)
                    if r in cand and r not in seen: seen.add(r); st.append(r)
        if len(comp) > len(best): best = comp
    return set(best)

def pack_fx(color, outdir):
    out = {}
    for key, ids in FX_SRC.items():
        ims = [Image.open(os.path.join(ROOT, 'assets/incoming/msv1/frames', color, i + '.png')).convert('RGBA') for i in ids]
        cw, ch = max(i.width for i in ims), max(i.height for i in ims)
        s = Image.new('RGBA', (cw * len(ims), ch), (0, 0, 0, 0))
        for k, i in enumerate(ims): s.alpha_composite(i, (k * cw + (cw - i.width) // 2, (ch - i.height) // 2))
        s.save(os.path.join(outdir, key + '.png')); out[key] = {'frames': len(ims), 'w': cw, 'h': ch}
    m = crescent_mask(); src = Image.open(os.path.join(ROOT, 'assets/incoming/msv1/frames', color, 'R15_03.png')).convert('RGBA')
    xs = [p[0] for p in m]; ys = [p[1] for p in m]; x0, y0 = min(xs), min(ys)
    c = Image.new('RGBA', (max(xs) - x0 + 1, max(ys) - y0 + 1), (0, 0, 0, 0))
    for (x, y) in m: c.putpixel((x - x0, y - y0), src.getpixel((x, y)))
    c.save(os.path.join(outdir, 'proj_crescent.png')); out['proj_crescent'] = {'frames': 1, 'w': c.width, 'h': c.height}
    return out

if __name__ == '__main__':
    fx = {}
    for color, key in (('red', 'ns_red'), ('yellow', 'ns_yellow')):
        fx[key] = pack_fx(color, os.path.join(ROOT, 'assets', key))
    assert fx['ns_red'] == fx['ns_yellow']
    with open(os.path.join(ROOT, 'msv1Sprites.js'), 'a') as fh:
        fh.write(f"export const MSV1_FX = {json.dumps(fx['ns_red'])}\n")
    print('fx', fx['ns_red'])
