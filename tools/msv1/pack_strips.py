"""MSV1: pack the cut Ninja Storm frames (assets/incoming/msv1/frames/<red|yellow>) into engine strips.
One geometry for both rangers (palette swap, proven in docs/msv1/SPRITE_MAP.md). Nearest-neighbour only, no scaling.
Usage: python3 tools/msv1/pack_strips.py <repo_root>"""
import json, sys, os
import numpy as np
from PIL import Image
ROOT = sys.argv[1] if len(sys.argv) > 1 else '.'
FR = os.path.join(ROOT, 'assets/incoming/msv1/frames')
OUT = os.path.join(ROOT, 'assets/incoming/msv1/sheets')
amap = json.load(open(os.path.join(ROOT, 'docs/msv1/ANIM_MAP.json')))
G = {a['anim']: a for a in amap}
def rng(anim, a=None, b=None, rev=False):
    g = G[anim]; a = g['a'] if a is None else g['a'] + a; b = g['b'] if b is None else g['a'] + b
    ids = [f"R{int(g['row'][1:]):02d}_{i:02d}" for i in range(a, b + 1)]
    return ids[::-1] if rev else ids
# (strip name, frame ids, speed (ticks/frame), loop)
STRIPS = {}
for g in amap: STRIPS[g['anim']] = (rng(g['anim']), 4, False)
STRIPS.update({
  'idle': (rng('idle'), 8, True), 'run': (rng('run'), 3, True), 'walk': (rng('run'), 5, True), 'walk_back': (rng('run', rev=True), 5, True),
  'dash': (rng('streak'), 2, True), 'streak': (rng('streak'), 2, True), 'jump': (rng('jump', 0, 3), 4, False), 'fall': (rng('jump', 4, 6), 5, False),
  'crouch': (rng('crouch'), 3, False), 'guard': (rng('guard'), 6, False), 'hurt': (rng('hurt'), 4, False), 'knockdown': (rng('knockdown'), 4, False),
  'getup': (rng('getUpRoll'), 3, False), 'win': (rng('victory'), 8, False), 'lose': (rng('knockdown', 8, 10), 8, False), 'intro': (rng('streak') + rng('skid') + rng('stance', 0, 1), 5, False),   # arrives as a Ninja Streak blur, skids to a stop
  'grab': (rng('punchAlt', 0, 1), 4, False), 'airSpin': (rng('airSpin'), 3, True), 'tornado': (rng('tornado'), 2, True), 'smoke': (rng('smoke'), 3, False),
  'smokeFade': (rng('smokeFade'), 4, False), 'dome': (rng('dome'), 3, True),
})
FX_ROWS = {'R03', 'R11', 'R19', 'R21', 'R23', 'R24'}
def anchor(img, fid):
    a = np.array(img)[:, :, 3] > 0
    ys, xs = np.where(a)
    if fid[:3] in FX_ROWS: return (xs.min() + xs.max() + 1) / 2
    top = ys.min(); band = a[top:top + 12]
    cx = np.where(band)[1].mean()
    return cx
meta = {}
for tag in ['red', 'yellow']:
    os.makedirs(os.path.join(OUT, tag), exist_ok=True)
    for name, (ids, speed, loop) in STRIPS.items():
        imgs = [Image.open(os.path.join(FR, tag, i + '.png')).convert('RGBA') for i in ids]
        # geometry from the RED sheet only (identical by proof) so both strips are byte-aligned
        if tag == 'red' or name not in meta:
            ax = [anchor(im, i) for im, i in zip(imgs, ids)]
            left = max(int(np.ceil(x)) for x in ax); right = max(int(np.ceil(im.width - x)) for im, x in zip(imgs, ax))
            half = max(left, right) + 2; H = max(im.height for im in imgs) + 2
            meta[name] = dict(ids=ids, ax=ax, cw=half * 2, ch=H, speed=speed, loop=loop)
        m = meta[name]; strip = Image.new('RGBA', (m['cw'] * len(imgs), m['ch']), (0, 0, 0, 0))
        for k, (im, x) in enumerate(zip(imgs, m['ax'])):
            strip.paste(im, (k * m['cw'] + int(round(m['cw'] / 2 - x)), m['ch'] - 1 - im.height), im)
        strip.save(os.path.join(OUT, tag, name + '.png'))
geo = {n: {'frames': len(m['ids']), 'width': m['cw'], 'height': m['ch'], 'originX': m['cw'] // 2, 'originY': m['ch'] - 1,
           'speed': m['speed'], 'loop': m['loop'], 'ids': m['ids']} for n, m in meta.items()}
js = ['// Generated by tools/msv1/pack_strips.py; do not hand-edit. One geometry for both Ninja Storm rangers (palette swap).',
      'export const NINJA_STORM_GEO = ' + json.dumps(geo, indent=1) + '',
      "const anim = dir => Object.fromEntries(Object.entries(NINJA_STORM_GEO).map(([k, g]) => [k, { sheet: `./assets/incoming/msv1/sheets/${dir}/${k}.png`, frames: g.frames, width: g.width, height: g.height, frameWidth: g.width, frameHeight: g.height, anchorY: 0, originX: g.originX, originY: g.originY, speed: g.speed, loop: g.loop, lockLastFrame: true }]))",
      "export const SHANE_ANIM = anim('red')", "export const DUSTIN_ANIM = anim('yellow')", '']
open(os.path.join(ROOT, 'msv1NinjaSprites.js'), 'w').write('\n'.join(js))
used = set(i for m in meta.values() for i in m['ids'])
print('strips', len(meta), 'distinct frames used', len(used))

# ── FX crops (sheet pixels only): keep pixels whose colour is IDENTICAL on both sheets (= not suit; palette-swap proof) ──
def fxcrop(fid, box, out):
    r = np.array(Image.open(os.path.join(FR, 'red', fid + '.png')).convert('RGBA'))
    y = np.array(Image.open(os.path.join(FR, 'yellow', fid + '.png')).convert('RGBA'))
    same = (r[:, :, :3] == y[:, :, :3]).all(2) & (r[:, :, 3] > 0)
    x0, y0, x1, y1 = box
    a = r.copy(); a[:, :, 3] = np.where(same, 255, 0)
    c = a[y0:y1, x0:x1]
    ys, xs = np.where(c[:, :, 3] > 0)
    c = c[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    Image.fromarray(c).save(os.path.join(OUT, out))
    return c.shape
print('crescent', fxcrop('R15_03', (46, 0, 67, 46), 'fx_crescent.png'))
print('kunai', fxcrop('R20_02', (33, 0, 42, 10), 'fx_kunai.png'))
