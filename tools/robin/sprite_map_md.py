#!/usr/bin/env python3
"""Generate docs/robin/SPRITE_MAP.md from docs/robin/source_rects.json + robinSprites.js + robinData.js TIMELINE (read via node)."""
import json, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
R = json.loads((ROOT / 'docs/robin/source_rects.json').read_text())
J = subprocess.run(['node', '--input-type=module', '-e', "import {ROBIN_ANIM} from './robinSprites.js'; import {TIMELINE, ROBIN_MOVES} from './robinData.js'; console.log(JSON.stringify({A: ROBIN_ANIM, T: TIMELINE, M: Object.keys(ROBIN_MOVES)}))"],
                   cwd=ROOT, capture_output=True, text=True, check=True).stdout
D = json.loads(J); A, T = D['A'], D['T']
cells = {c['name']: c for c in R['cells']}
USE = {
 'intro': 'Match intro: Appearing (with the ROBIN — THE BOY WONDER card)', 'introSettle': 'Intro settle into the idle stance',
 'idle': 'Neutral stance (loop)', 'walk': 'Walk forward (run cycle at walk speed)', 'walk_back': 'Walk back', 'run': 'Run', 'dash': 'Ordinary dash',
 'rStep': 'Smoke Step (enhanced dash) + ult reposition', 'jump': 'Jump rise', 'doubleJump': 'Shared double jump (second half of the Jumping row)',
 'fall': 'Fall', 'land': 'Landing sequence after a genuine landing', 'crouch': 'Crouch', 'guard': 'Guard', 'hurt': 'Hit reaction', 'knockdown': 'Knockdown',
 'lose': 'Defeat (Defeated row)', 'win': 'Victory', 'light': 'Punch 1 (back-fist)', 'rJ2': 'Punch 2 (straight)', 'rJ3': 'Punch 3 (rising finisher)',
 'rLow': 'Low staff check', 'heavy': 'Staff Sweep', 'up': 'Pole-vault launcher', 'rAdv': 'Advancing staff lunge → stow', 'air': 'Midair Kick',
 'rBomb': "Bird's-Eye Bomb (ground throw)", 'rAirBomb': 'Air bomb (down-forward)', 'rSmoke': 'Smoke Drop', 'rPlant': 'Dead Drop (plant)',
 'rExpress': 'Staff Express (Play-3-Times flurry ×3 → push)', 'rRoof': 'Rooftop Route (rising staff → airborne finish)', 'rHack': 'Remote Override (Hacking Computer)',
 'rStaffEnd': 'Staff end pose (reserve strip)', 'rStow': 'Staff stow (reserve strip)', 'ultOpen': 'Ultimate opener (row-1 sweep)', 'ultPose': 'Ultimate cut-in pose',
 'ultFlurry': 'Ultimate staff flurry', 'ultRise': 'Ultimate rising staff', 'ultHack': 'Ultimate wrist-computer command', 'ultLeap': 'Ultimate leap clear of the blast', 'ultLand': 'Ultimate landing',
}
L = ['# Robin — sprite map', '',
 f"Source: `{R['source']}` — {R['size'][0]}×{R['size'][1]} {R['mode']}, SHA-256 `{R['sha256']}`.",
 f"Background key: {R['keyPolicy']}. Labels / section rules / the credit panel are excluded (`{R['credit']}`).",
 f"Credit panel rect {R['creditPanel']} is shown only through credits.js, never in gameplay art.", '',
 f"Every body cell is pasted into a common **{R['frame']['width']}×{R['frame']['height']}** frame with the anchor (head centre x, band floor y) at "
 f"**({R['frame']['originX']}, {R['frame']['originY']})** → `ROBIN_CELL`, so every strip shares one pivot (no foot slide between actions). "
 f"Measured reach: {json.dumps(R['reach'])}. Nearest-neighbour only; pixels are never redrawn.", '',
 f"Coverage: {len(R['cells'])} cells extracted, **unused body cells: {len(R['unusedBodyCells'])}** (every group has a reachable purpose).", '',
 'Generated by `tools/robin/sprite_map_md.py` (rects: `docs/robin/source_rects.json`; contact sheets: `contact_sheet.png`, `contact_sheet_fx_icons.png`, `transitions.png`).', '',
 '## Actions (strip → source cells → timing)', '',
 '| action | use | frames (source cells) | loop | speed / timeline (tick → frame) |', '|---|---|---|---|---|']
for k, a in A.items():
    seq = R['sequences'].get(k, [])
    tl = T.get(k)
    tls = ('timeline ' + ', '.join(f"{t}→{f}" for t, f in tl[:14]) + (' …' if len(tl) > 14 else '')) if tl else f"{a['speed']} ticks / frame"
    L.append(f"| `{k}` | {USE.get(k, '')} | {a['frames']}: {' '.join(seq)} | {'yes' if a['loop'] else 'no'} | {tls} |")
L += ['', '## Source cells', '', '| cell | rect [x0,y0,x1,y1] | anchor | used in |', '|---|---|---|---|']
for c in R['cells']:
    if c.get('kind') != 'body': continue
    L.append(f"| {c['name']} | {c['rect']} | {c.get('anchor')} | {', '.join(c.get('usedIn', []))} |")
L += ['', '## Icons, cut-in and effects', '',
 f"- Health-icon expressions: `assets/robin/icons/expressions.png` — {json.dumps(R['icons'])[:400]}",
 f"- Cut-in bust + mask / mouth overlays: `assets/robin/cutscene/` — {json.dumps(R['cutscene'])[:400]}",
 f"- Effects: {json.dumps(R['fx'])[:600]}",
 '- `fx/smoke_strip.png` = explosion cells 5–9 remapped by luminance to a grey-slate ramp (alpha 200): the supplied art has no separate smoke cloud.',
 '- `fx/blank.png` = 1×1 transparent sheet for the invisible blast hit-volume (the visible 11-cell explosion is drawn by robinFx).', '']
(ROOT / 'docs/robin/SPRITE_MAP.md').write_text('\n'.join(L) + '\n')
print(len(L), 'lines')
