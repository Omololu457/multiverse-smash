#!/usr/bin/env python3
"""gen_spd_red_skins.py — S.P.D. Red Ranger alt skins (cosmetic only).

    python3 tools/spd_red_build/gen_spd_red_skins.py <repo root>

Every shipped sheet except the WANTED poster and the gem crops is recoloured as `<sheet>__<tag>.png`.
The S.P.D. Red art uses a tiny, exact palette (verified: 29 colours across all body sheets), so the recolour is an
EXACT palette map — no thresholds, no hue guessing, no repainting:

  * SUIT  = the red ramp  (255,8,0) (222,8,0) (189,8,0) (181,0,0) (165,0,0) (132,0,0) (123,16,8) (107,0,0) (99,0,0)
  * TRIM  = the white/grey ramp (247,255,231) (198,198,181) (148,148,140) (99,99,90) (49,49,41)
  * black outlines / visor / sleeves (0,0,0) (8,8,8) and every other colour are left exactly as they are.

Each ramp maps by its brightness onto a light→dark target ramp, so the shading survives. The poster's own colours
((130,0,0) red, tans, cyan gem) are not in either ramp, so the composed portrait recolours only the body.
"""
import os, sys
from PIL import Image

ROOT = sys.argv[1]
SRC = os.path.join(ROOT, 'assets', 'spd_red')
SKIP = {'poster.png', 'gem.png', 'gem_cut.png'}

SUIT = [(255, 8, 0), (222, 8, 0), (189, 8, 0), (181, 0, 0), (165, 0, 0), (132, 0, 0), (123, 16, 8), (107, 0, 0), (99, 0, 0)]
TRIM = [(247, 255, 231), (198, 198, 181), (148, 148, 140), (99, 99, 90), (49, 49, 41)]

# tag: (suit light, suit dark) , (trim light, trim dark) or None = keep
SKINS = {
    'green':     ((70, 235, 70),   (0, 70, 12),    None),                              # S.P.D. Green (Bridge)
    'yellow':    ((255, 228, 40),  (125, 80, 0),   None),                              # S.P.D. Yellow (Z)
    'pink':      ((255, 120, 195), (115, 10, 70),  None),                              # S.P.D. Pink (Syd)
    'shadow':    ((44, 60, 150),   (3, 5, 28),     ((235, 238, 250), (40, 44, 60))),   # Shadow Ranger (Doggie Cruger)
    'swat':      ((160, 14, 26),   (36, 0, 6),     ((112, 118, 130), (18, 20, 26))),   # S.W.A.T. Mode (gunmetal)
    'battlizer': None,                                                                 # (filled below: red + gold)
    'asquad':    ((96, 96, 108),   (12, 12, 18),   ((255, 44, 32), (90, 0, 0))),       # A-Squad (Rogue): black suit, red trim
    'albedo':    ((246, 246, 240), (108, 108, 104), ((255, 34, 24), (70, 0, 0))),      # Albedo: white suit, red trim
    'ben10':     ((76, 80, 76),    (12, 14, 12),   ((140, 255, 90), (8, 92, 10))),     # Ben 10: black + Omnitrix green
    'alienx':    ((34, 34, 50),    (3, 3, 9),      ((255, 255, 255), (165, 168, 190))),  # Alien X: void body (engine starfield overlay)
}
SKINS['battlizer'] = ((255, 8, 0), (99, 0, 0), ((255, 232, 120), (112, 70, 8)))         # Red Battlizer: red + gold armour trim

def lum(c): return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]

def ramp_map(src, light, dark):
    ls = [lum(c) for c in src]; hi, lo = max(ls), min(ls)
    out = {}
    for c, l in zip(src, ls):
        t = (l - lo) / (hi - lo) if hi > lo else 1.0          # 1 = brightest
        out[c] = tuple(round(dark[i] + (light[i] - dark[i]) * t) for i in range(3))
    return out

def build_map(spec):
    suit, sd, trim = spec[0], spec[1], spec[2]
    m = ramp_map(SUIT, suit, sd)
    if trim: m.update(ramp_map(TRIM, trim[0], trim[1]))
    return m

def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith('.png') and '__' not in f and f not in SKIP)
    n = 0
    for tag, spec in SKINS.items():
        m = build_map(spec)
        for f in files:
            im = Image.open(os.path.join(SRC, f)).convert('RGBA')
            px = im.load()
            for y in range(im.height):
                for x in range(im.width):
                    p = px[x, y]
                    if p[3] == 0: continue
                    c = m.get(p[:3])
                    if c: px[x, y] = (c[0], c[1], c[2], p[3])
            im.save(os.path.join(SRC, f.replace('.png', f'__{tag}.png')), optimize=True)
            n += 1
    print(f'{len(SKINS)} skins x {len(files)} sheets = {n} files')
    write_ledger(files)

NAMES = {'green': 'S.P.D. Green (Bridge)', 'yellow': 'S.P.D. Yellow (Z)', 'pink': 'S.P.D. Pink (Syd)', 'shadow': 'Shadow Ranger (Doggie Cruger)',
         'swat': 'S.W.A.T. Mode', 'battlizer': 'Red Battlizer', 'asquad': 'A-Squad (Rogue)', 'albedo': 'Albedo', 'ben10': 'Ben 10', 'alienx': 'Alien X'}
def hexc(c): return '#%02x%02x%02x' % c
def write_ledger(files):
    # (re)write the generated "Alt skins" section of docs/spd_red/SPRITE_LEDGER.md: every derived file named.
    path = os.path.join(ROOT, 'docs', 'spd_red', 'SPRITE_LEDGER.md')
    led = open(path).read()
    mark = '\n## Alt skins (derived recolours)\n'
    if mark in led: led = led[:led.index(mark)]
    out = [mark, 'Generated by `tools/spd_red_build/gen_spd_red_skins.py`. Every file below is a **derived copy** of the same-named base sheet: an exact palette map of the red suit ramp and the white/grey trim ramp onto a light-to-dark target ramp. Alpha, size, black outlines, visor, poster and gem are unchanged. No pixel is moved or invented. Verified by `harness/spd_red_skins_check.mjs`.', '',
           '| Tag | Skin | Suit ramp (light → dark) | Trim ramp | Files |', '|---|---|---|---|---|']
    for tag, spec in SKINS.items():
        trim = f'{hexc(spec[2][0])} → {hexc(spec[2][1])}' if spec[2] else 'unchanged'
        out.append(f'| `{tag}` | {NAMES[tag]} | {hexc(spec[0])} → {hexc(spec[1])} | {trim} | ' + ', '.join(f.replace('.png', f'__{tag}.png') for f in files) + ' |')
    open(path, 'w').write(led.rstrip('\n') + '\n' + '\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
