// tools/stage_cards.mjs — render a STAGE-SELECT card picture for every stage from the real in-game background (2026-11-25
// polish pass: several stage cards showed only a flat sky strip / blank because their preview.png is just the far layer).
// Boots a real match on each stage, lets the layered art load, then draws ONLY the battle background (ui.drawBattleBackground
// under the live camera, no fighters / HUD) into an offscreen canvas and saves stages/cards/<slug>.jpg + stageCards.js.
// Run: node tools/stage_cards.mjs [only=Name1,Name2]
import { chromium } from 'playwright'
import fs from 'node:fs'
import { serve } from '../harness/ben10_test_utils.mjs'
const ROOT = new URL('..', import.meta.url).pathname
const OUT = ROOT + 'stages/cards/'; fs.mkdirSync(OUT, { recursive: true })
const only = (process.argv.find(a => a.startsWith('only=')) || '').slice(5).split(',').filter(Boolean)
const slug = n => n.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '')
const server = await serve(), browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
await page.goto(`${server.base}/index.html?harness=1&p1=goku&p2=naruto&seed=5`, { timeout: 400000, waitUntil: 'domcontentloaded' })
await page.waitForFunction(() => window.__harness?.start, null, { timeout: 400000 })
const STAGES = (await page.evaluate(() => __harness.kevinTest.stages())).map(name => ({ name }))
let manifest = {}
try { manifest = (await import(ROOT + 'stageCards.js')).STAGE_CARDS || {} } catch (_) {}
manifest = { ...manifest }
for (const st of STAGES) {
  if (only.length && !only.includes(st.name)) continue
  if (st.name === 'My Location' || st.name === 'Multiverse Roulette') continue   // live / random by design: keep their own card
  await page.evaluate(n => { __harness.start({ stage: n }); __harness.skipToBattle?.() }, st.name)
  await page.waitForTimeout(6000)
  const data = await page.evaluate(async () => {
    const st = __harness.kevinTest.stageTheme()
    const ui = await import('/ui.js'), { camera } = await import('/camera.js')
    const cv = document.querySelector('canvas'), W = cv.width, H = cv.height
    const off = document.createElement('canvas'); off.width = W; off.height = H
    const g = off.getContext('2d'), floorH = st.floorHeight || 120, groundY = H - floorH - (typeof st.groundOffset === 'number' ? st.groundOffset : 100)
    const half = (H / (camera.zoom || 1)) / 2
    camera.applyTransform?.(g, cv)
    ui.drawBattleBackground(g, cv, st, groundY, floorH, { top: camera.y - half - 160, bottom: camera.y + half + 160 })
    camera.clearTransform?.(g)
    // the card is ~2.1:1 — crop so the floor line sits ~82 % down the card
    const cw = W, chh = Math.round(W / 2.1), gy = (groundY - (camera.y - (camera.shakeY || 0))) * (camera.zoom || 1) + H / 2, sy = Math.max(0, Math.min(H - chh, Math.round(gy - chh * 0.82)))
    const c2 = document.createElement('canvas'); c2.width = 640; c2.height = Math.round(640 / 2.1)
    c2.getContext('2d').drawImage(off, 0, sy, cw, chh, 0, 0, c2.width, c2.height)
    return c2.toDataURL('image/jpeg', 0.86)
  })
  const f = 'stages/cards/' + slug(st.name) + '.jpg'
  fs.writeFileSync(ROOT + f, Buffer.from(data.split(',')[1], 'base64'))
  manifest[st.name] = f
  console.log('card', st.name, '→', f)
}
fs.writeFileSync(ROOT + 'stageCards.js', '// stageCards.js — GENERATED by tools/stage_cards.mjs: stage name → the select-card picture rendered from the real\n' +
  '// in-game background (ui.js drawStageSelectScreen prefers it over the stage\'s preview.png). Presentation only.\n' +
  'export const STAGE_CARDS = ' + JSON.stringify(manifest, null, 1) + '\n')
await browser.close(); server.close?.(); process.exit(0)
