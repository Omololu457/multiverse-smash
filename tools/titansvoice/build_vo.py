#!/usr/bin/env python3
"""Teen Titans voice: cut Beast Boy / Robin / Raven / Starfire / Cyborg voice clips out of the supplied compilations and
write titansVoiceData.js (audio-only pools).

  python3 tools/titansvoice/build_vo.py [source-dir]      (default: ~/Downloads)

tools/titansvoice/curation.json holds every chosen clip (pool, start / duration in its source, transcript). Each clip is
loudness-normalised (EBU R128 -16 LUFS) to mono 44.1 kHz MP3 → assets/audio/titans/<key>/tt_NNN.mp3. Deterministic.
"""
import json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CUR = json.load(open(os.path.join(os.path.dirname(__file__), 'curation.json')))
SRC_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Downloads')
JS = os.path.join(ROOT, 'titansVoiceData.js')


def main():
    lines = ['// Generated by tools/titansvoice/build_vo.py — do not hand-edit. Teen Titans voice pools (AUDIO-ONLY, no gameplay',
             '// effect), cut from the supplied voice compilations and transcribed offline (tools/titansvoice/curation.json).',
             '// Each entry: [file, transcript, seconds]. "vs:<key>" pools play only against that Titan.',
             'export const TITANS_VOICE = {']
    total = 0
    for key, c in CUR['chars'].items():
        src = os.path.join(SRC_DIR, c['source'])
        if not os.path.exists(src): sys.exit(f'source not found: {src}')
        out = os.path.join(ROOT, 'assets', 'audio', 'titans', key); os.makedirs(out, exist_ok=True)
        done = set()
        lines.append(f'  {key}: {{')
        for pool, items in c['pools'].items():
            for e in items:
                name = f"tt_{e['i']:03d}.mp3"
                if name not in done:
                    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f"{e['start']:.3f}", '-t', f"{e['dur']:.3f}", '-i', src,
                                    '-af', 'loudnorm=I=-16:TP=-1.5:LRA=11,afade=t=in:d=0.01,areverse,afade=t=in:d=0.03,areverse',
                                    '-ac', '1', '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', '80k', os.path.join(out, name)], check=True)
                    done.add(name)
            lines.append(f'    {json.dumps(pool)}: [' + ', '.join(json.dumps([f'./assets/audio/titans/{key}/tt_{e["i"]:03d}.mp3', e['text'], round(e['dur'], 2)], ensure_ascii=False) for e in items) + '],')
        lines.append('  },')
        total += len(done)
    lines.append('}')
    open(JS, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{total} clips → assets/audio/titans/*; wrote titansVoiceData.js')


if __name__ == '__main__':
    main()
